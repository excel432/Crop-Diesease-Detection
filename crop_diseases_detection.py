from tensorflow.keras.preprocessing.image import ImageDataGenerator

dataset_path = 'plant-disease-detection-dataset/Dataset'

datagen = ImageDataGenerator(
    rescale = 1./255,
    validation_split = 0.2
)

# Training data
train_data = datagen.flow_from_directory(
    dataset_path,
    target_size = (224, 224),
    batch_size = 32,
    class_mode = 'categorical',
    subset = 'training'
)

# Validation
val_data = datagen.flow_from_directory(
    dataset_path,
    target_size = (224, 224),
    batch_size = 32,
    class_mode = 'categorical',
    subset = 'validation'
)
print(f"Training images: {train_data.samples}")
print(f"Validation images: {val_data.samples}")
print(f"Disease classes: {train_data.num_classes}")

from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras import layers, models

# Load mobileNetV2 as base
base_model = MobileNetV2(
    input_shape = (224, 224, 3),
    include_top = False,
    weights = 'imagenet'
)

base_model.trainable = False

model = models.Sequential([
    base_model,
    layers.GlobalAveragePooling2D(),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.3),
    layers.Dense(train_data.num_classes, activation='softmax')
])

# Compile model
model.compile(
    optimizer = 'adam',
    loss = 'categorical_crossentropy',
    metrics = ['accuracy']
)

# Train model
history = model.fit(
    train_data,
    validation_data = val_data,
    epochs = 10,
)

print(f"Training complete!")

import matplotlib.pyplot as plt

# Plot accuracy
